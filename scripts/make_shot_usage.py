fmtcam = lambda k: f"lon {k[1]:.2f}, lat {k[2]:.2f}, zoom {k[3]:.2f}, pitch {k[4]:.0f}°, bearing {k[5]:.0f}°"
def motion(s):
    ks = s['keys']; a, b = ks[0], ks[-1]
    t = []
    d = lambda j: abs(b[j] - a[j])
    if d(3) > 0.3: t.append('zoom ' + ('in' if b[3] > a[3] else 'out') + f' {d(3):.2f} levels')
    if d(1) > 0.05 or d(2) > 0.05: t.append(f'pan {((d(1)*0.82)**2 + d(2)**2) ** .5:.1f}°')
    if d(4) > 1: t.append(f'tilt {a[4]:.0f}→{b[4]:.0f}°')
    if d(5) > 1: t.append(f'rotate {a[5]:.0f}→{b[5]:.0f}°')
    # direction changes across keys (not a one-direction drift)
    ch = 0
    for j in range(1, 6):
        v = [ks[i+1][j] - ks[i][j] for i in range(len(ks)-1)]
        v = [x for x in v if abs(x) > 1e-6]
        ch += sum(1 for i in range(len(v)-1) if v[i]*v[i+1] < 0)
    return ' + '.join(t) or 'NONE', ch

